/**
 * The label for a province or city name from cities.ts: the stored Chinese name in
 * Chinese, the English label in English. A name with no label (one saved before the
 * list changed, say) is shown as stored.
 */
export function placeLabel(name: string, locale: Locale): string {
  if (locale === 'zh') return name;
  // hasOwn rather than a bare lookup, so a stored value such as "constructor" can't
  // resolve to an Object.prototype member.
  return Object.hasOwn(PLACE_EN, name) ? PLACE_EN[name] : name;
}
